test('preparation failure replaces old completion status and retry preserves the prior run', async ({ page }, info) => {
  await seedWorkspace(page, { runCount: 1, itemCount: 0, providerBaseUrl: 'http://127.0.0.1:4173/__synthetic/fail' })
  await openWorkspace(page)
  const status = page.getByTestId('run-status')
  await expect(status).toHaveCount(1)
  await expect(status).toHaveAttribute('data-status', 'completed')
  const [previousRun] = await readRecords(page, 'runs')
  expect(previousRun.status).toBe('completed')

  await page.getByRole('button', { name: 'Keep current', exact: true }).click()
  await page.getByRole('button', { name: 'Improve prompt', exact: true }).click()
  await expect(status).toHaveCount(1)
  await expect(status).toHaveAttribute('data-status', 'error')
  await expect(status.getByRole('alert')).toContainText('Synthetic provider failure')
  expect(await readRecords(page, 'runs')).toEqual([previousRun])
  expect(await readRecords(page, 'datasets_items')).toHaveLength(0)

  // Reopening the still-available prior revision must not reintroduce its
  // completed marker alongside the current preparation error.
  await page.getByTestId('run-result').getByRole('button', { name: 'Review changes', exact: true }).click()
  await expect(page.getByTestId('result-prompt')).toBeVisible()
  await expect(status).toHaveCount(1)
  await expect(status).toHaveAttribute('data-status', 'error')
  await expect(status.getByRole('alert')).toContainText('Synthetic provider failure')
  await attachScreenshot(page, info, 'preparation-error-after-completed-run', false)

  await page.getByRole('button', { name: 'Configure models', exact: true }).click()
  const configuration = page.getByRole('dialog', { name: 'Configure models', exact: true })
  await configuration.getByRole('button', { name: 'Use demo', exact: true }).click()
  await configuration.getByRole('button', { name: 'Save models', exact: true }).click()
  await page.getByRole('button', { name: 'Keep current', exact: true }).click()
  await page.getByRole('button', { name: 'Improve prompt', exact: true }).click()
  await expect(status).toHaveAttribute('data-status', 'running')
  await expect(status).toHaveAttribute('data-status', 'completed', { timeout: 30_000 })
  await expect(status).toHaveCount(1)
  const runs = await readRecords(page, 'runs')
  expect(runs).toHaveLength(2)
  expect(runs.find((run) => run.id === previousRun.id)).toEqual(previousRun)
  expect(runs.find((run) => run.id !== previousRun.id)?.status).toBe('completed')
  expect((await readRecords(page, 'datasets_items')).length).toBeGreaterThanOrEqual(2)
})
