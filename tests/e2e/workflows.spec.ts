async function replacePrompt(page: Page, text: string) {
  const editor = page.getByRole('textbox', { name: 'Your prompt', exact: true })
  await expect(editor).toHaveAttribute('contenteditable', 'true')
  await editor.focus()
  await page.keyboard.press('ControlOrMeta+A')
  await page.keyboard.insertText(text)
  await expect(editor).toHaveText(text)
}

async function expectPromptDocument(page: Page, expected: string) {
  const editor = await showPromptEditor(page)
  // CodeMirror renders logical lines as adjacent block elements. The parent's
  // textContent concatenates them without newlines; reconstruct the document
  // from its logical lines rather than normalizing away missing separators.
  await expect.poll(async () => (await editor.locator('.cm-line').allTextContents()).join('\n')).toBe(expected)
}

async function expectPersistedPrompt(page: Page, taskId: string, expected: string) {
  await expect.poll(async () => (await readRecords(page, 'tasks')).find((task) => task.id === taskId)?.initialPrompt).toBe(expected)
}

async function tabTo(page: Page, target: Locator, direction: 'Tab' | 'Shift+Tab' = 'Tab') {
  for (let index = 0; index < 60; index += 1) {
    if (await target.evaluate((element) => element === document.activeElement)) return
    await page.keyboard.press(direction)
  }
  throw new Error(`Could not reach ${await target.getAttribute('aria-label') || await target.textContent()} using ${direction}`)
}

