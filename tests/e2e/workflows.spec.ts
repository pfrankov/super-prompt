test('latest prompt persists across immediate navigation, reload, and reopening', async ({ page }) => {
  await seedWorkspace(page)
  await openWorkspace(page)
  const afterNavigation = 'This edit must survive immediate tab navigation.'
  await replacePrompt(page, afterNavigation)
  // Intentionally do not wait for the old 500ms debounce before unmounting.
  await selectTaskSection(page, 'History')
  await selectTaskSection(page, 'Improve')
  await expect(page.getByRole('textbox', { name: 'Your prompt', exact: true })).toHaveText(afterNavigation)
  const afterReload = 'This final edit must survive an immediate page reload.'
  await replacePrompt(page, afterReload)
  page.once('dialog', (dialog) => void dialog.accept())
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Your prompt', exact: true })).toHaveText(afterReload)
  await page.goto('/')
  await page.getByRole('button', { name: /Synthetic prompt fixture/ }).click()
  await openPromptMenu(page)
  await expect(page.getByRole('navigation', { name: 'Prompt navigation', exact: true }).getByRole('link', { name: 'Improve', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('textbox', { name: 'Your prompt', exact: true })).toHaveText(afterReload)
  expect((await readRecords(page, 'tasks')).find((task) => task.id === TASK_ID)?.initialPrompt).toBe(afterReload)
})

